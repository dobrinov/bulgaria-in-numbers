// Наети от държавата и колко струват — общи данни за „Бюджет“ и „Администрация“.
import { YEARS } from '../lib/format.js';

// Евростат gov_10a_main, D1 (възнаграждения с осигуровките на работодателя), сектор „Държавно управление“, млрд. €, 2015–2025
export const PAY = [4.2682, 4.3411, 4.7982, 5.3275, 6.1409, 6.6419, 7.8818, 8.6567, 9.9898, 11.8863, 14.3575];

// НСИ, наети в обществения сектор (средногодишно)
export const PY = [2020, 2021, 2022, 2023, 2024];
export const PUB = [537437, 540890, 545083, 550445, 561551];
export const ALL = [2211773, 2248934, 2278832, 2302922, 2323880];
// НСИ, средна месечна брутна заплата за страната, лв. (2020–2024)
export const NAT_WAGE_BGN = [1391, 1561, 1770, 2040, 2325];

/** Разход за заплати на един нает в обществения сектор, € на месец (оценка); j е индекс в PY. */
export function perEmployee(j) {
  return (PAY[YEARS.indexOf(PY[j])] * 1e9) / PUB[j] / 12;
}
